export type AutomationsMessageKey = keyof typeof AUTOMATIONS_MESSAGES_ES

export function makeT(t?: TranslateFn) {
  return (key: AutomationsMessageKey, vars?: Record<string, string | number>) => {
    const fallback: string = AUTOMATIONS_MESSAGES_ES[key]
    let s = t ? t(key, fallback) : fallback
    if (!s || s === key) s = fallback
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{{${k}}}`, String(v))
    return s
  }
}

export type AutomationsT = ReturnType<typeof makeT>
