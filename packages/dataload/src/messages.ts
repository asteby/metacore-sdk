export type DataloadMessageKey = keyof typeof DATALOAD_MESSAGES_ES

export function makeT(t?: TranslateFn) {
  return (key: DataloadMessageKey, vars?: Record<string, string | number>) => {
    const fallback: string = DATALOAD_MESSAGES_ES[key]
    let s = t ? t(key, fallback) : fallback
    if (!s || s === key) s = fallback
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{{${k}}}`).join(String(v))
    return s
  }
}

export type DataloadT = ReturnType<typeof makeT>
