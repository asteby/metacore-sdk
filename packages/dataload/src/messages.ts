/** Built-in catalogs by locale. A host adds or replaces one through `messages` (or `DataloadProvider`). */
export const DATALOAD_CATALOGS: Record<string, DataloadMessages> = {
  'es-MX': DATALOAD_MESSAGES_ES_MX,
  'en-US': DATALOAD_MESSAGES_EN_US,
}

/** Picks the built-in catalog for a BCP 47 locale: any `en*` -> en-US, anything else -> es-MX. */
export function catalogFor(locale?: string): DataloadMessages {
  if (locale && DATALOAD_CATALOGS[locale]) return DATALOAD_CATALOGS[locale]!
  return locale?.toLowerCase().startsWith('en') ? DATALOAD_MESSAGES_EN_US : DATALOAD_MESSAGES_ES_MX
}

export interface DataloadI18n {
  locale?: string
  /** A whole catalog or a few keys; wins over the built-in one. */
  messages?: Partial<DataloadMessages>
  /** Host translator (e.g. i18next): receives the key and the catalog text as fallback. */
  t?: TranslateFn
}

export function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s
  for (const [k, v] of Object.entries(vars)) s = s.split(`{{${k}}}`).join(String(v))
  return s
}

/**
 * Translator used by every component. Order: `messages[key]` -> `t(key, catalog text)`
 * -> built-in catalog for `locale`. A `t` that answers with the key itself (a
 * missing translation in most i18n libraries) falls back to the catalog.
 */
export function makeT(t?: TranslateFn, opts: Omit<DataloadI18n, 't'> = {}) {
  const catalog = catalogFor(opts.locale)
  const messages = opts.messages
  return (key: DataloadMessageKey, vars?: Record<string, string | number>) => {
    const own = messages?.[key]
    if (own) return interpolate(own, vars)
    const base: string = catalog[key] ?? DATALOAD_MESSAGES_ES_MX[key] ?? key
    let s = t ? t(key, base) : base
    if (!s || s === key) s = base
    return interpolate(s, vars)
  }
}

export type DataloadT = ReturnType<typeof makeT>
