export const MESSAGES: Record<Locale, Messages> = { en: en as unknown as Messages, es }

export type TFunction = (key: MessageKey, vars?: Record<string, string | number>) => string

/** `overrides` lets the host rename or translate any key (e.g. other locales). */
export function createT(locale: Locale = 'es', overrides?: Partial<Messages>): TFunction {
  const base = MESSAGES[locale] ?? MESSAGES.en
  return (key, vars) => {
    const raw = overrides?.[key] ?? base[key] ?? MESSAGES.en[key] ?? key
    return vars ? raw.replace(/\{\{(\w+)\}\}/g, (_, k: string) => String(vars[k] ?? '')) : raw
  }
}
