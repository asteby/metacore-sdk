export type TFn = (key: string, vars?: Record<string, unknown>) => string

function interpolate(s: string, vars?: Record<string, unknown>): string {
    if (!vars) return s
    return s.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])))
}

/** Resolves the bundled text for `lang` (es default; any `en*` → English). */
export function defaultMessage(key: string, lang?: string): string {
    const dict = lang && lang.toLowerCase().startsWith('en') ? SETUP_MESSAGES_EN : SETUP_MESSAGES_ES
    return dict[key] ?? SETUP_MESSAGES_ES[key] ?? key
}

/**
 * Translator for the setup components. Keys that start with `setup.` (or are
 * the shared `installed_addons.*` / `common.*` ones) go through i18next first,
 * so a host can override; the bundled es/en text is the default value.
 * Interpolation is done here too, so it works even without an i18next instance.
 */
export function useSetupT(): TFn {
    const { t, i18n } = useTranslation()
    const lang = i18n?.language
    return useCallback(
        (key, vars) => {
            const hostKey = key.includes('.') && /^(installed_addons|common)\./.test(key) ? key : `setup.${key}`
            const fallback = defaultMessage(key, lang)
            const out = t(hostKey, { ...(vars ?? {}), defaultValue: fallback }) as string
            // Mocked / minimal `t` implementations may ignore interpolation.
            return interpolate(typeof out === 'string' ? out : fallback, vars)
        },
        [t, lang],
    )
}
