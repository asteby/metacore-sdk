#!/usr/bin/env node
// metacore-tailwind-sources check|write [--css <file>] [--root <dir>]
//
// Tailwind v4 does not scan node_modules, so every `@asteby/*` SDK package an
// app depends on that emits classes needs an `@source` (or the app imports
// `@asteby/metacore-theme/sources.css`). A missing one ships unstyled UI.
//   check  exits 1 and lists the SDK dependencies with no `@source` coverage.
//   write  writes `<css dir>/metacore-sources.css` with app-relative `@source`
//          lines for the app's SDK dependencies (import it from the stylesheet).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { METACORE_TAILWIND_SOURCE_PACKAGES } from '../tailwind-sources.js'

const [cmd, ...rest] = process.argv.slice(2)
const arg = (name, def) => {
  const i = rest.indexOf(name)
  return i >= 0 ? rest[i + 1] : def
}
const root = path.resolve(arg('--root', process.cwd()))
const cssPath = path.resolve(root, arg('--css', 'src/styles/index.css'))

if (!['check', 'write'].includes(cmd)) {
  console.error('usage: metacore-tailwind-sources check|write [--css src/styles/index.css] [--root .]')
  process.exit(2)
}

const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
const deps = new Set(
  Object.keys({ ...pkg.dependencies, ...pkg.devDependencies, ...pkg.peerDependencies })
)
const needed = METACORE_TAILWIND_SOURCE_PACKAGES.filter((n) => deps.has(n))

if (cmd === 'write') {
  const out = path.join(path.dirname(cssPath), 'metacore-sources.css')
  const lines = needed.map((n) => {
    const rel = path.relative(path.dirname(cssPath), path.join(root, 'node_modules', n))
    return `@source "${rel.split(path.sep).join('/')}";`
  })
  writeFileSync(
    out,
    `/* GENERATED by metacore-tailwind-sources write — do not edit. */\n${lines.join('\n')}\n`
  )
  console.log(`wrote ${path.relative(root, out)} (${needed.length} @source)`)
  process.exit(0)
}

if (!existsSync(cssPath)) {
  console.error(`css not found: ${cssPath}`)
  process.exit(2)
}
// Follow relative @import chains so a generated/imported sources file counts.
const seen = new Set()
const collect = (file) => {
  if (seen.has(file) || !existsSync(file)) return ''
  seen.add(file)
  const text = readFileSync(file, 'utf8')
  let all = text
  for (const m of text.matchAll(/@import\s+['"](\.[^'"]+)['"]/g)) {
    all += '\n' + collect(path.resolve(path.dirname(file), m[1]))
  }
  return all
}
const css = collect(cssPath)
// Importing the theme's sources.css covers every SDK package.
if (/@import\s+['"]@asteby\/metacore-theme\/sources\.css['"]/.test(css)) {
  console.log('ok: @asteby/metacore-theme/sources.css imported')
  process.exit(0)
}
const covered = (n) => css.split('\n').some((l) => /@source/.test(l) && l.includes(n))
const missing = needed.filter((n) => !covered(n))
if (missing.length) {
  console.error(
    `Tailwind @source missing for SDK dependencies (classes would be dropped):\n` +
      missing.map((n) => `  - ${n}`).join('\n') +
      `\nFix: @import '@asteby/metacore-theme/sources.css'; or run \`metacore-tailwind-sources write\` and import the result.`
  )
  process.exit(1)
}
console.log(`ok: ${needed.length} SDK dependencies covered by @source`)
