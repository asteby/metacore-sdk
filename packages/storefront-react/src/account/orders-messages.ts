/** Messages for a locale (`es*` default, `en*`), with optional per-key overrides. */
export function accountMessages(locale?: string | null, overrides?: Partial<AccountMessages> | null): AccountMessages {
  const base: AccountMessages = (locale ?? 'es-MX').toLowerCase().startsWith('en') ? EN : ES
  return overrides ? { ...base, ...overrides } : base
}

/** Text for an open enum: `<group>.<value>` when this SDK knows it, else `<group>.unknown`. Never the raw value. */
export function enumText(m: AccountMessages, group: string, value: unknown): string {
  const key = `${group}.${typeof value === 'string' ? value : ''}` as AccountMessageKey
  return Object.prototype.hasOwnProperty.call(m, key) ? m[key] : m[`${group}.unknown` as AccountMessageKey]
}
