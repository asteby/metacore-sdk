export type ReviewsMessages = typeof es
export type ReviewsMessageKey = keyof ReviewsMessages

/** The messages of a locale (`en*` → English, anything else → Spanish) with the host's overrides on top. */
export function reviewsMessages(locale: string, overrides?: Partial<ReviewsMessages>): ReviewsMessages {
  const base = /^en\b/i.test(locale) ? en : es
  return overrides ? { ...base, ...overrides } : base
}

export function fillReviewsText(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_m, k: string) => String(vars[k] ?? ''))
}
