#!/usr/bin/env node
// Generates the list of SDK packages that emit Tailwind classes (any
// `className=` / `cva(` in `packages/*/src`) and the artefacts derived from it:
//   - packages/theme/styles/sources.css        (`@source` per package)
//   - packages/starter-config/tailwind-sources.js (+ .d.ts) (list for the app-side checker)
// `--check` exits 1 when a committed artefact is stale (CI).
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkgsDir = path.join(root, 'packages')
const CLASS_RE = /className=|\bcva\(|\bclass=/
const isTest = (f) => /(\.test\.|\.stories\.|__tests__|\.d\.ts)/.test(f)

function emitsClasses(dir) {
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      const full = path.join(d, n)
      const st = statSync(full)
      if (st.isDirectory()) {
        if (walk(full)) return true
      } else if (/\.(tsx|ts|jsx|js)$/.test(n) && !isTest(full)) {
        if (CLASS_RE.test(readFileSync(full, 'utf8'))) return true
      }
    }
    return false
  }
  const src = path.join(dir, 'src')
  return existsSync(src) && walk(src)
}

const packages = []
for (const d of readdirSync(pkgsDir).sort()) {
  const pj = path.join(pkgsDir, d, 'package.json')
  if (!existsSync(pj)) continue
  const meta = JSON.parse(readFileSync(pj, 'utf8'))
  if (meta.private || !meta.name?.startsWith('@asteby/')) continue
  if (emitsClasses(path.join(pkgsDir, d))) packages.push(meta.name)
}

const short = (n) => n.replace('@asteby/', '')
const cssOut = `/*
 * GENERATED by scripts/gen-tailwind-sources.mjs — do not edit.
 *
 * Tailwind v4 skips node_modules, so classes used by SDK packages (compiled
 * JSX) are not generated unless the app declares an @source for each one.
 * Import this file once from the app stylesheet:
 *
 *   @import '@asteby/metacore-theme/sources.css';
 *
 * Paths are relative to this file (…/@asteby/metacore-theme/styles). Under pnpm
 * the real path of the theme package only sees its own siblings; if classes are
 * still missing run \`metacore-tailwind-sources write\` (starter-config), which
 * emits app-relative @source lines, and \`metacore-tailwind-sources check\` in CI.
 */
${packages.map((n) => `@source "../../${short(n)}";`).join('\n')}
`
const jsOut = `// GENERATED by scripts/gen-tailwind-sources.mjs — do not edit.
// SDK packages that emit Tailwind classes and therefore need an \`@source\` in the app.
export const METACORE_TAILWIND_SOURCE_PACKAGES = ${JSON.stringify(packages, null, 2)}
`
const dtsOut = `// GENERATED by scripts/gen-tailwind-sources.mjs — do not edit.
export declare const METACORE_TAILWIND_SOURCE_PACKAGES: string[]
`
const files = [
  [path.join(pkgsDir, 'theme/styles/sources.css'), cssOut],
  [path.join(pkgsDir, 'starter-config/tailwind-sources.js'), jsOut],
  [path.join(pkgsDir, 'starter-config/tailwind-sources.d.ts'), dtsOut],
]

if (process.argv.includes('--check')) {
  const stale = files.filter(([f, c]) => !existsSync(f) || readFileSync(f, 'utf8') !== c)
  if (stale.length) {
    console.error(
      `stale: ${stale.map(([f]) => path.relative(root, f)).join(', ')}\nrun: node scripts/gen-tailwind-sources.mjs`
    )
    process.exit(1)
  }
  console.log(`tailwind sources up to date (${packages.length} packages)`)
} else {
  for (const [f, c] of files) writeFileSync(f, c)
  console.log(`wrote ${files.length} files (${packages.length} packages)`)
}
